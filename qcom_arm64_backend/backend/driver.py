class CPUUtils(object):
    def __new__(cls):
        if not hasattr(cls, "instance"):
            cls.instance = super(CPUUtils, cls).__new__(cls)
        return cls.instance

    # Note:
    # nvidia and amd backends have their corresponding driver.c file that exposes
    # get_device_properties and load_binary using python bindings.
    # (see third_party/nvidia/backend/driver.c)
    # These methods are then used in compiler.py to initialize handles before running
    # the triton kernels.
    # Since we recompile the kernel every time (see compile_module above),
    # and the metadata generated by these functions aren't applicable to the cpu
    # backend, just define the same functions with dummy implementation.
    @staticmethod
    def get_device_properties(device):
        return {
          "max_shared_mem": 2 ** 20,
          "multiprocessor_count": None,
          "sm_clock_rate": None,
          "mem_clock_rate": None,
          "mem_bus_width": None,
          "neon_vector_size": 32,
          "sve_vector_size": 128,
          "sme_array_size": 128
        }

    # Important note:
    # Since we cannot easy pass function pointers around, we pass along the
    # assembly source code so that compile_module above can recompile the
    # module every time.
    @staticmethod
    def load_binary(name, kernel_asm, shared, device):
        return (
          None,       # module
          kernel_asm, # function
          None,       # n_regs
          None,       # n_spills
          sys.maxsize # n_max_threads
        )

def _get_device_dir(file_name) -> str:
    usr = os.environ["USER"]
    DEVICE_PATH=f"/data/data/{usr}/triton/{file_name}"
    return DEVICE_PATH

def _get_staging_dir(exec_name) -> str:
    staging_dir_top = utils.get_env_var("TRITON_ARM64_STAGING_DIR")
    STAGING_DIR=os.path.join(staging_dir_top, exec_name)
    return STAGING_DIR

def _run_command(command, env):
    if (utils.get_verbose_level() > 1):
        print("    command:", command)

    command_list=command.split()
    try:
        subprocess.run(
            command_list,
            shell=False,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            env=env,
            text=True,
        )
    except subprocess.CalledProcessError as e:
        print(command)
        print(f"Error executing the command: {e}")
        for line in e.output.splitlines():
          print(f"{line}")
        sys.exit(1)

class ARM64Executor(object):
    def __init__(self, exec_mode):
        self.exec_mode = exec_mode
        self.verbose_level = utils.get_verbose_level()

    def build_standalone_exec(self, kernel_name, compiled_kernel, launcher_src, const_ll_paths=""):
        #call clang++ with generated launcher c++ and kernel asm
        build_dir = utils.get_work_dir()
        kernel_path = os.path.join(build_dir, f"{kernel_name}.ll")
        launcher_path = os.path.join(build_dir, f"{kernel_name}_launcher.cpp")
        prof_path = utils.get_env_var("ARM64_BACKEND_PATH") + "/backend/lib/prof.cpp"
        exec_path = os.path.join(build_dir, f"{kernel_name}.exe")
        Path(kernel_path).write_text(compiled_kernel)
        Path(launcher_path).write_text(launcher_src)

        arm64_backend_inc_path = utils.get_env_var("ARM64_BACKEND_PATH") + "/backend/include"
        triton_shared_inc_path = utils.get_env_var("TRITON_SHARED_ROOT") + "/backend/include"
        gcc_toolchain_path = utils.get_env_var("ARM64_TOOLCHAIN_DIR")
        INCLUDES = f"-I{arm64_backend_inc_path} -I{triton_shared_inc_path}"
        ARM64_CXX_FLAGS = f"-O3 --target=aarch64-linux-gnu -march=armv8.5a+sve2+sme"
        sysroot_path = os.path.join(gcc_toolchain_path, "aarch64-none-linux-gnu", "libc")
        TOOLCHAIN_FLAGS = f"--sysroot={sysroot_path} --gcc-toolchain={gcc_toolchain_path}"
        launcher_libpaths = ["-L" + libpath for libpath in utils.get_env_var("LAUNCHER_LIBPATHS", "").split()]
        LIBPATH = " ".join(launcher_libpaths)
        LIBS = f"-lclang_rt.builtins-aarch64 -lstdc++ -lunwind"
        compile_env = os.environ.copy()
        llvm_bin_path = utils.get_env_var("LLVM_BINARY_DIR")
        compile_env["PATH"] = f"{llvm_bin_path}:{compile_env['PATH']}"
        debug_flags = "-g" if utils.get_debug_mode() else ""
        compile_command = "{} {} {} {} {} {} {} {} {} {} -static -fPIC {} -o {}".format(
                        "clang++",
                        ARM64_CXX_FLAGS,
                        INCLUDES,
                        TOOLCHAIN_FLAGS,
                        kernel_path,
                        const_ll_paths,
                        launcher_path,
                        prof_path,
                        LIBPATH,
                        LIBS,
                        debug_flags,
                        exec_path,
        )
        if self.verbose_level:
            const_module_text = " with constant modules" if const_ll_paths else ""
            print(f"\n==> Compiling {kernel_path} and {launcher_path} {const_module_text}")

        _run_command(compile_command, compile_env)
        return exec_path
    
    def run_standalone(self, file_name, exec_path, input_tensor_paths, output_tensor_paths, exec_dir, benchmark_mode, profile_mode):

        if self.verbose_level: print("==> File Name:", file_name)
        #run on qemu or device
        run_env=os.environ.copy()
        if self.exec_mode == "simulator":
            qemu_path = utils.get_env_var("QEMU_PATH")
            run_command=f"{qemu_path} {exec_path}"
            if self.verbose_level:
                print("==> Exec_mode: qemu, QEMU PATH:", qemu_path)
            _run_command(run_command, run_env)
        else:
            exec_name = os.path.basename(exec_path)
            ADB = utils.get_env_var("ADB_PATH")
            HOST = utils.get_env_var("DEV_HOST")
            DEVICE_ID = utils.get_env_var("DEV_ID")
            DEVICE_PATH =_get_device_dir(file_name)
            print("==> DEVICE_PATH:", DEVICE_PATH)
            STAGING_DIR = _get_staging_dir(exec_name.split('.')[0])

            if self.verbose_level:
                print("==> Exec_mode: device, HOST:", HOST, "DEVICE:", DEVICE_ID, "PATH:", DEVICE_PATH)
                print("==> Copying executable and input tensors files to staging area:", STAGING_DIR)

            os.makedirs(STAGING_DIR, exist_ok=True)
            shutil.copy(exec_path, STAGING_DIR)
            for input_tensor in input_tensor_paths:
                shutil.copy(input_tensor, STAGING_DIR)

            SSH_ADB_COMMAND = f"ssh {HOST} {ADB} -s {DEVICE_ID}"
            commands = [
                f"{SSH_ADB_COMMAND} shell 'rm -rf {DEVICE_PATH}'",
                f"{SSH_ADB_COMMAND} shell 'mkdir -p {DEVICE_PATH}'"
            ]
            #push executable and input tensor files to device
            commands.append(
                f"{SSH_ADB_COMMAND} push {STAGING_DIR}/{exec_name} {DEVICE_PATH}"
            )
            for input_path in input_tensor_paths:
                input_filename = os.path.basename(input_path)
                commands.append(
                    f"{SSH_ADB_COMMAND} push {STAGING_DIR}/{input_filename} {DEVICE_PATH}"
                )
            #change permission and run the executable
            commands.append(
                f"{SSH_ADB_COMMAND} shell 'chmod 755 {DEVICE_PATH}/{exec_name}'"
            )
            commands.append(
                f"{SSH_ADB_COMMAND} shell '{DEVICE_PATH}/{exec_name}'"
            )

            for output_path in output_tensor_paths:
                output_filename = os.path.basename(output_path)
                commands.append(
                    f"{SSH_ADB_COMMAND} pull {DEVICE_PATH}/{output_filename} {STAGING_DIR}"
                )

            if benchmark_mode[0]:
                commands.append(
                    f"{SSH_ADB_COMMAND} pull {DEVICE_PATH}/benchmark.log {STAGING_DIR}"
                )

            # pull profiling report off android device
            if profile_mode:
                commands.append(
                    f"{SSH_ADB_COMMAND} pull {DEVICE_PATH}/prof_report.json {STAGING_DIR}"
                )

            if self.verbose_level:
                print("==> Running the kernel on device ...")
            for command in commands:
                _run_command(command, run_env)

            if self.verbose_level:
                print("==> Retrieving output tensors files from staging area:", STAGING_DIR)
            for output_path in output_tensor_paths:
                output_filename = os.path.basename(output_path)
                shutil.copy(os.path.join(STAGING_DIR, output_filename), exec_dir)

            if benchmark_mode[0]:
                shutil.copy(os.path.join(STAGING_DIR, "benchmark.log"), exec_dir)

            # copy report to exec dir and generate final .csv output
            if profile_mode:
                staging_report_path = os.path.join(STAGING_DIR, "prof_report.json")
                shutil.copy(staging_report_path, exec_dir)
                # TODO: if infodump path is changed in ARM64ProfInstrumentation.cpp
                #       this path will also need to be changed
                prof_infodump_path = "/tmp/prof_infodump.txt"
                prof_csv_path = os.path.join(STAGING_DIR, "prof_output.csv")
                process_prof.process_prof_data(staging_report_path,
                                               prof_infodump_path,
                                               prof_csv_path, None)
                shutil.copy(prof_csv_path, exec_dir)

    def get_results(self, input_tensor_paths, file_name, exec_dir):
        #collect output tensor files
        output_paths = []
        for i in range(len(input_tensor_paths)):
            output_path = os.path.join(
                exec_dir, f"{file_name}_o{i}.raw"
            )
            output_paths.append(output_path)
        results = []
        for i in range(len(input_tensor_paths)):
            output_path = output_paths[i]
            with open(output_path, "rb") as file:
                out_dtype_id = struct.unpack("I", file.read(4))[0]
                out_dtype = utils.to_torch_type(out_dtype_id)
                out_rank = struct.unpack("q", file.read(8))[0]
                out_shape = [
                    struct.unpack("q", file.read(8))[0] for _ in range(out_rank)
                ]
                out_data = file.read()
                output_torch_tensor = torch.frombuffer(
                    np.array(out_data), dtype=out_dtype
                )  #  cast to numpy and then passed to torch to suppress torch warning
                output_torch_tensor = output_torch_tensor.reshape(out_shape)
                results.append(output_torch_tensor)
        return results

class ARM64Launcher(object):
    def __init__(self, src, metadata):
        self.kernel_name = src.fn.__name__
        self.verbose_level = utils.get_verbose_level()
        cst_key = lambda i: src.fn.arg_names.index(i) if isinstance(i, str) else i
        self.input_type_list = {cst_key(key): value for key, value in src.signature.items()}
        pass

    def __call__(self, *args, **kwargs):
        # args =  grid_0, grid_1, grid_2, stream, kernel.function,
        #         kernel.packed_metadata, launch_metadata,
        #         CompiledKernel.launch_enter_hook,
        #         CompiledKernel.launch_exit_hook, *args
        kernel_llir = args[4]
        num_fixed_args = 9
        inputs_with_constants = list(args[num_fixed_args:])
        inputs = [ inp for idx,inp in enumerate(inputs_with_constants) if not self.input_type_list[idx] == "constexpr"]
        launch_grid = (args[0], args[1], args[2])
        file_name = self.kernel_name
        exec_mode = utils.get_exec_mode()
        host_dir = utils.get_work_dir()
        device_dir = _get_device_dir(file_name)
        benchmark_mode = utils.get_benchmark_mode(exec_mode)
        profile_mode = utils.get_profile_mode(exec_mode)

        arm64generator = WrapperGenerator(
            inputs, [], kernel_llir, file_name, launch_grid, exec_mode, benchmark_mode,
            profile_mode, device_dir if exec_mode == "device" else host_dir, True
            )
        # Generate launcher c++ src
        launcher_src = arm64generator.generate_standalone_launcher()

        # print("------", launcher_src, "\n--------")

        # Dump tensor inputs to file
        input_tensor_paths = arm64generator.dump_tensor_inputs(host_dir)

        arm64executor = ARM64Executor(exec_mode)
        # Compile launcher c++ and kernel asm
        arm64exec = arm64executor.build_standalone_exec(file_name, kernel_llir, launcher_src)
        if self.verbose_level:
            print(f"==> Running {arm64exec}")

        output_paths = []
        for i in range(len(input_tensor_paths)):
            output_path = os.path.join(
                _get_staging_dir(os.path.basename(arm64exec).split('.')[0]), f"{file_name}_o{i}.raw"
            )
            output_paths.append(output_path)

        # Run compiled kernel in standalone mode
        arm64executor.run_standalone(file_name, arm64exec, input_tensor_paths, output_paths, host_dir, benchmark_mode, profile_mode)
        if self.verbose_level:
            print(f"==> Ran successfully, collecting results")
        # Collect results and overwrite input tensors
        output_tensors = arm64executor.get_results(input_tensor_paths, file_name, host_dir)
        assert len(output_tensors), len(arm64generator.num_input_tensors)
        res_idx = 0
        for inp in arm64generator.input_profs:
            if inp.input_type == "tensor":
                inputs[inp.input_id].copy_(output_tensors[res_idx])
                res_idx += 1
        if self.verbose_level:
            print(f"==> Results copied")

        if benchmark_mode[0]:
            with open(f"{host_dir}/benchmark.log", 'r') as file:
                benchmark_data = file.read()
            print(benchmark_data)

class ARM64TorchLauncher(object):
    def __init__(self, func_name, input_profs, return_types):
        self.kernel_name = func_name
        self.verbose_level = utils.get_verbose_level()
        self.input_profs = input_profs
        self.return_types = return_types

    def invoke(self, llir_path, inputs, const_llir_paths: list[str] = []):
        exec_mode = utils.get_exec_mode()
        host_dir = utils.get_work_dir()
        device_dir = _get_device_dir(self.kernel_name)
        benchmark_mode = utils.get_benchmark_mode(exec_mode)
        profile_mode = utils.get_profile_mode(exec_mode)
        file_name = self.kernel_name
        launch_grid = (1, 1, 1) # No Triton tiling
        with open(llir_path, 'r') as file:
            llir = file.read()

        arm64generator = WrapperGenerator(
            inputs, self.return_types, llir, file_name, launch_grid, exec_mode, benchmark_mode,
            profile_mode, device_dir if exec_mode == "device" else host_dir, True
            )

        # Generate launcher c++ src
        launcher_src = arm64generator.generate_standalone_launcher()

        # Dump tensor inputs to file and determine output paths
        input_tensor_paths = arm64generator.dump_tensor_inputs(host_dir)
        output_paths = [os.path.join(host_dir, f"{self.kernel_name}_o{i}.raw") for i in range(len(self.return_types))]

        # Compile launcher c++ and kernel asm (with optional constant modules)
        arm64executor = ARM64Executor(exec_mode)
        arm64exec = arm64executor.build_standalone_exec(
            file_name, llir, launcher_src, " ".join(const_llir_paths)   
        )
        
        if self.verbose_level:
            print(f"==> Running {arm64exec}")

        # Run compiled kernel in standalone mode
        arm64executor.run_standalone(file_name, arm64exec, input_tensor_paths, output_paths, host_dir, benchmark_mode, profile_mode)
        if self.verbose_level:
            print(f"==> Ran successfully, collecting results")

        # Collect results and overwrite input tensors
        output_tensors = arm64executor.get_results(output_paths, file_name, host_dir)

        assert len(output_tensors), len(arm64generator.output_profs)

        if benchmark_mode[0]:
            with open(f"{host_dir}/benchmark.log", 'r') as file:
                benchmark_data = file.read()
            print(benchmark_data)

        return output_tensors

def ty_to_cpp(ty):
    return {
        "i1": "int32_t",
        "i8": "int8_t",
        "i16": "int16_t",
        "i32": "int32_t",
        "i64": "int64_t",
        "u1": "uint32_t",
        "u8": "uint8_t",
        "u16": "uint16_t",
        "u32": "uint32_t",
        "u64": "uint64_t",
        "fp16": "float",
        "bf16": "float",
        "fp32": "float",
        "f32": "float",
        "fp64": "double",
    }[ty]


class ARM64CPUDriver(DriverBase):
    def __init__(self, vector_ext):
        self.utils = CPUUtils()
        self.backend = "ARM64CPU"
        self.launcher_cls = ARM64Launcher
        self.binary_ext = "cpuasm"
        # ARM64 vector extension, valid values are: neon, sve, sme
        # Note: sme includes sve2, which includes sve
        # TODO: add sme2 when target hardware supports that feature
        if vector_ext in ["neon", "sve", "sme"]:
            self.vector_ext = vector_ext
        else:
            self.vector_ext = "sme"

        self.verbose_level = utils.get_verbose_level()
        if self.verbose_level:
            print("ARM64CPUDriver initialized with vector extension:", self.vector_ext)

    @staticmethod
    def is_active():
        return True

    def map_python_to_cpp_type(self, ty: str) -> str:
        return ty_to_cpp(ty)

    def get_benchmarker(self):
        from triton.testing import do_bench

    def get_device_capability(self):
        return self.vector_ext

    def get_current_stream(self, device):
        return None

    def get_active_torch_device(self):
        import torch
        return torch.device("cpu")

    def get_current_device(self):
        return GPUTarget("arm64", self.vector_ext, 0)

    def get_current_target(self):
        return GPUTarget("arm64", self.vector_ext, 0)
